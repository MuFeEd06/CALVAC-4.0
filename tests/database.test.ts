import { test, before, after, beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

let db: PGlite;
const customer = { name: 'Audit Customer', phone: '9876543210', line1: 'Street', line2: '', city: 'City', state: 'State', pin: '123456', landmark: '' };
const item = { productId: '1', quantity: 1, size: '8', sizeUnit: 'UK', color: 'Red' };
const order = async (items = [item], key = 'test-idempotency-0001') => (await db.query<{result: any}>(
  'select public.create_order_with_stock_v2($1::jsonb,$2::jsonb,$3) as result', [JSON.stringify(items), JSON.stringify(customer), key])).rows[0].result;
const stock = async () => (await db.query<{stock: Record<string, number>}>('select stock from products where id=1')).rows[0].stock;
const migration = () => readFile(new URL('../supabase/migrations/202610190001_checkout_hardening.sql', import.meta.url), 'utf8');

async function fixture(jsonType: 'json' | 'jsonb' = 'jsonb') {
  const database = new PGlite();
  await database.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    grant usage on schema public to anon, authenticated, service_role;
    create table products (
      id bigint generated by default as identity primary key, name text, brand text, price numeric, original_price numeric,
      image text, tag text, category text, size_unit text default 'UK', sizes text[], colors ${jsonType} default '[]',
      stock ${jsonType} default '{}', total_stock integer, active boolean default true, out_of_stock boolean default false, specs text
    );
    create table orders (
      id bigint generated by default as identity primary key, name text, phone text, line1 text, line2 text,
      city text, state text, pin text, landmark text, total numeric, status text, items ${jsonType}, notes text,
      created_at timestamptz default now()
    );
    create table site_settings (id bigint primary key, data jsonb);
    create table offer (id bigint primary key, active boolean, text text, bg_color text, text_color text, show_logo boolean);
    grant all on products, orders, site_settings, offer to anon, authenticated;
    alter table site_settings enable row level security;
    create policy legacy_open_settings on site_settings for all using (true) with check (true);
  `);
  await database.exec(await migration());
  return database;
}
before(async () => {
  db = await fixture();
});
after(async () => { await db?.close(); });
beforeEach(async () => {
  await db.exec(`truncate orders, products, checkout_idempotency restart identity cascade;
    insert into products(id,name,brand,price,image,sizes,colors,stock,total_stock) values
    (1,'Sneaker','Audit',100,'/shoe.webp',array['8'], '[{"name":"Red","price":150},{"name":"Blue","price":null}]', '{"default|8":5}', 5);`);
});

test('migration computes authoritative color pricing and replays the same order without decrementing twice', async () => {
  const first = await order();
  assert.equal(Number(first.total), 150);
  assert.equal(first.items[0]._stock_key, undefined);
  assert.deepEqual(await order(), first);
  assert.equal((await stock())['default|8'], 4);
  assert.equal((await db.query('select * from orders')).rows.length, 1);
  await assert.rejects(order([{ ...item, quantity: 2 }]), /already used/);
});

test('shared stock is checked across all cart lines and the whole transaction rolls back on failure', async () => {
  await assert.rejects(order([{ ...item, quantity: 3 }, { ...item, color: 'Blue', quantity: 3 }]), /Insufficient stock/);
  assert.equal((await stock())['default|8'], 5);
  assert.equal((await db.query('select * from orders')).rows.length, 0);
  assert.equal((await db.query('select * from checkout_idempotency')).rows.length, 0);
  assert.ok((await order()).id, 'failed attempts must not consume the key');
});

test('invalid variants and unavailable products are rejected by the transaction', async () => {
  await assert.rejects(order([{ ...item, size: '99' }]), /Invalid product size/);
  await assert.rejects(order([{ ...item, color: 'Missing' }]), /Invalid product color/);
  await assert.rejects(order([{ ...item, sizeUnit: 'EU' }]), /Invalid product size/);
  await db.exec('update products set active=false where id=1');
  await assert.rejects(order(), /Product is unavailable/);
});

test('cancellation restores inventory once and invalid status transitions are rejected', async () => {
  const created = await order();
  const status = (value: string) => db.query('select public.set_order_status_v2($1,$2)', [created.id, value]);
  await assert.rejects(status('Delivered'), /Invalid order status transition/);
  await status('Cancelled'); await status('Cancelled');
  assert.equal((await stock())['default|8'], 5);
  assert.equal(Number((await db.query('select total_stock from products where id=1')).rows[0].total_stock), 5);
  await assert.rejects(status('Confirmed'), /Invalid order status transition/);
});

test('anonymous access hides inactive products and denies order reads, writes and privileged RPCs', async () => {
  await db.exec(`insert into products(id,name,active) values (2,'Hidden',false); set role anon;`);
  try {
    assert.equal((await db.query('select id from products')).rows.length, 1);
    await assert.rejects(db.query('select * from orders'), /permission denied/);
    await assert.rejects(db.query('update products set price=1 where id=1'), /permission denied/);
    await assert.rejects(order(), /permission denied/);
  } finally { await db.exec('reset role'); }
});

test('transaction supports JSON legacy columns as well as JSONB', async () => {
  const legacy = await fixture('json');
  try {
    await legacy.exec(`insert into products(id,name,price,image,sizes,colors,stock,total_stock) values
      (1,'Legacy Sneaker',100,'/shoe.webp',array['8'],'[{"name":"Red","price":150}]','{"default|8":5}',5);`);
    const created = (await legacy.query<{result: any}>(
      'select public.create_order_with_stock_v2($1::jsonb,$2::jsonb,$3) as result',
      [JSON.stringify([item]), JSON.stringify(customer), 'test-legacy-json-0001'])).rows[0].result;
    assert.equal(Number(created.total), 150);
    await legacy.query('select public.set_order_status_v2($1,$2)', [created.id, 'Cancelled']);
    assert.equal((await legacy.query<{stock: Record<string, number>}>('select stock from products where id=1')).rows[0].stock['default|8'], 5);
  } finally { await legacy.close(); }
});

test('public settings remain readable but cannot be changed through legacy permissive policies', async () => {
  await db.exec(`insert into site_settings values (1,'{"store_name":"Audit"}'); set role authenticated;`);
  try {
    assert.equal((await db.query('select data from site_settings')).rows.length, 1);
    await assert.rejects(db.query(`update site_settings set data='{}'`), /permission denied/);
    await assert.rejects(db.query(`insert into offer(id,text) values(1,'Injected')`), /permission denied/);
  } finally { await db.exec('reset role'); }
});

test('migration preserves relational order history and supports the exact live schema with JSON text columns', async () => {
  const live = new PGlite();
  try {
    await live.exec('create role anon; create role authenticated; create role service_role bypassrls; grant usage on schema public to anon,authenticated,service_role;');
    await live.exec(await readFile(new URL('./fixtures/live-schema.sql', import.meta.url), 'utf8'));
    await live.exec(`
      insert into products(id,name,brand,price,image,sizes,colors,stock) values
        (1,'Fixture Sneaker','Audit',100,'/shoe.webp','["UK 8"]','[{"name":"Red","price":150}]','{"default|UK 8":5}');
      insert into orders(id,name,phone,line1,city,state,pin,total,status) values
        (900,'Historical Fixture','9876543210','Street','City','State','123456',100,'Pending');
      insert into order_items(id,order_id,product_id,name,brand,size,qty,price) values
        (900,900,1,'Historical Sneaker','Audit','UK 8',1,100);
    `);
    await live.exec(await migration());
    const historical = (await live.query<{items:any[]}>('select items from orders where id=900')).rows[0];
    assert.equal(historical.items[0].name, 'Historical Sneaker');
    assert.equal(historical.items[0].size, '8');
    assert.equal((await live.query('select * from order_items')).rows.length, 1);
    await assert.rejects(live.query(`select public.set_order_status_v2(900,'Cancelled')`), /manual inventory review/);
    const created = (await live.query<{result:any}>(
      'select public.create_order_with_stock_v2($1::jsonb,$2::jsonb,$3) as result',
      [JSON.stringify([item]), JSON.stringify({ ...customer, line1: 'Long fixture address '.repeat(9) }), 'live-schema-fixture-0001'])).rows[0].result;
    assert.equal(Number(created.total), 150);
    assert.equal(JSON.parse((await live.query<{stock:string}>('select stock from products where id=1')).rows[0].stock)['default|UK 8'], 4);
    assert.ok((await live.query('select created_at from orders where id=$1',[created.id])).rows[0].created_at);
    await live.query('select public.set_order_status_v2($1,$2)',[created.id,'Cancelled']);
    assert.equal(JSON.parse((await live.query<{stock:string}>('select stock from products where id=1')).rows[0].stock)['default|UK 8'], 5);
    await live.exec('set role anon');
    await assert.rejects(live.query('select * from order_items'), /permission denied/);
    await assert.rejects(live.query(`update settings set value=''`), /permission denied/);
  } finally { await live.close(); }
});
